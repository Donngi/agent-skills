// -------------------------------------------------
// 型定義
// -------------------------------------------------

/**
 * SystemClock
 * 実行環境の時刻を返す。
 */
export type SystemClock = Readonly<{
	/** 現在の Unix epoch ミリ秒 */
	now: () => number;
}>;

// -------------------------------------------------
// 実装
// -------------------------------------------------

export function createSystemClock(): SystemClock {
	return {
		now: () => Date.now(),
	};
}
